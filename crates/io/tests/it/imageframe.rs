//! IMAGEFRAME: the drawing's raster image frame mode, saved in the RASTERVARIABLES object's
//! group 70 and named by the `ACAD_IMAGE_VARS` dictionary entry. It is a drawing setting, so it is
//! written and read back with and without images; a file that sets no usable mode leaves the
//! default (1), and a value another reader could not use is written as that default. Pixels,
//! placement and clipping are unaffected by the mode.

use cadcraft_doc::{Common, Drawing, EntityKind, Image, Space, Viewport};
use cadcraft_geom::{Vec2, Vec3};
use cadcraft_io::{SaveOptions, plotter, read, write};
use serde_json::json;

/// A 4 x 3 pixel image of `map.png` at (10, 20), rotated a quarter turn, clipped to a triangle.
fn image() -> Image {
    Image {
        insert: Vec3::new(10.0, 20.0, 0.0),
        u: Vec3::new(0.0, 2.0, 0.0),
        v: Vec3::new(-2.0, 0.0, 0.0),
        size: Vec2::new(4.0, 3.0),
        path: "maps/map.png".into(),
        name: "map".into(),
        clip: vec![Vec2::new(-0.5, -0.5), Vec2::new(3.5, -0.5), Vec2::new(-0.5, 2.5)],
        clipping: true,
        fade: 25,
        brightness: 10,
        contrast: 90,
        ..Image::default()
    }
}

fn drawing(frame: Option<i64>, with_image: bool) -> Drawing {
    // Only drawings generated by this suite reach its DWG bridge.
    cadcraft_io::dwg_worker::allow_in_process();
    let mut d = Drawing::new_imperial();
    if let Some(f) = frame {
        d.header.set_i64("IMAGEFRAME", f);
    }
    if with_image {
        d.add(&Space::Model, Common::default(), EntityKind::Image(image())).unwrap();
    }
    d
}

/// The mode `d` holds, the way the renderer reads it.
fn mode(d: &Drawing) -> i64 {
    d.header.i64("IMAGEFRAME", 1)
}

/// The drawing's IMAGE entity, if it has one.
fn image_of(d: &Drawing) -> Option<Image> {
    d.model.iter().find_map(|e| match &e.kind {
        EntityKind::Image(i) => Some(i.clone()),
        _ => None,
    })
}

/// `d`'s (group code, value) pairs, as a file holds them. Written files are ASCII DXF.
fn groups(bytes: &[u8]) -> Vec<(i32, String)> {
    let text = String::from_utf8_lossy(bytes);
    let mut lines = text.lines().map(str::trim);
    let mut out = Vec::new();
    while let (Some(code), Some(value)) = (lines.next(), lines.next()) {
        if let Ok(code) = code.parse::<i32>() {
            out.push((code, value.to_string()));
        }
    }
    out
}

/// The records of a section of a written file: (type, groups after it).
fn records(tags: &[(i32, String)], section: &str) -> Vec<(String, Vec<(i32, String)>)> {
    let mut out = Vec::new();
    let mut in_section = false;
    let mut current: Option<(String, Vec<(i32, String)>)> = None;
    for (i, (code, value)) in tags.iter().enumerate() {
        if *code == 0 {
            if let Some(r) = current.take() {
                out.push(r);
            }
            match value.as_str() {
                "SECTION" => {
                    in_section = tags.get(i + 1).is_some_and(|(c, v)| *c == 2 && v == section);
                    continue;
                }
                "ENDSEC" => {
                    in_section = false;
                    continue;
                }
                _ => {}
            }
            if in_section {
                current = Some((value.clone(), Vec::new()));
            }
            continue;
        }
        if let Some((_, body)) = current.as_mut() {
            body.push((*code, value.clone()));
        }
    }
    if let Some(r) = current {
        out.push(r);
    }
    out
}

/// The RASTERVARIABLES record of a written file: its group 70, and whether the root (named object)
/// dictionary names `ACAD_IMAGE_VARS` and `ACAD_IMAGE_DICT`.
fn written(bytes: &[u8]) -> (i64, bool, bool) {
    let tags = groups(bytes);
    let objects = records(&tags, "OBJECTS");
    let rastvars: Vec<&Vec<(i32, String)>> = objects.iter().filter(|(k, _)| k == "RASTERVARIABLES").map(|(_, g)| g).collect();
    assert_eq!(rastvars.len(), 1, "one RASTERVARIABLES object");
    let frame = rastvars[0].iter().find(|(c, _)| *c == 70).and_then(|(_, v)| v.parse().ok()).expect("group 70");
    let root = objects.first().map(|(_, g)| g.as_slice()).unwrap_or_default();
    let key = |name: &str| root.windows(2).any(|w| w[0] == (3, name.to_string()));
    (frame, key("ACAD_IMAGE_VARS"), key("ACAD_IMAGE_DICT"))
}

#[track_caller]
fn same_image(want: &Image, got: &Image, what: &str) {
    let close = |a: Vec3, b: Vec3| (a - b).len() < 1e-9;
    assert!(close(want.insert, got.insert) && close(want.u, got.u) && close(want.v, got.v), "{what}: placement {got:?}");
    assert!((want.size - got.size).len() < 1e-9, "{what}: size {:?}", got.size);
    assert_eq!(want.clip.len(), got.clip.len(), "{what}: clip boundary length");
    for (a, b) in want.clip.iter().zip(&got.clip) {
        assert!((*a - *b).len() < 1e-9, "{what}: clip point {b:?} is not {a:?}");
    }
    assert_eq!(want.clipping, got.clipping, "{what}: clipping on");
    assert_eq!((want.fade, want.brightness, want.contrast), (got.fade, got.brightness, got.contrast), "{what}: fade and tone");
    assert_eq!(want.path, got.path, "{what}: file");
    assert_eq!(want.name, got.name, "{what}: definition name");
}

#[test]
fn every_mode_round_trips_through_dxf_dwg_and_dwt_with_and_without_images() {
    for with_image in [false, true] {
        for frame in [0, 1, 2] {
            let d = drawing(Some(frame), with_image);
            for name in ["frame.dxf", "frame.dwg", "frame.dwt"] {
                let bytes = write(&d, name).unwrap_or_else(|e| panic!("{name}: {e}"));
                let r = read(&bytes, name).unwrap_or_else(|e| panic!("{name}: {e}"));
                assert_eq!(mode(&r), frame, "{name}, images: {with_image}");
                match (with_image, image_of(&r)) {
                    (true, Some(i)) => same_image(&image(), &i, name),
                    (true, None) => panic!("{name}: the image is gone"),
                    (false, i) => assert!(i.is_none(), "{name}: an image appeared"),
                }
            }
        }
    }
}

#[test]
fn the_written_dxf_holds_the_mode_in_rastervariables_and_the_dictionary_names_it() {
    for with_image in [false, true] {
        for frame in [0, 1, 2] {
            let bytes = write(&drawing(Some(frame), with_image), "frame.dxf").unwrap();
            let (written_frame, named, image_dict) = written(&bytes);
            assert_eq!(written_frame, frame, "images: {with_image}");
            assert!(named, "the root dictionary names ACAD_IMAGE_VARS");
            assert_eq!(image_dict, with_image, "ACAD_IMAGE_DICT stays conditional on images");
            // The class record a reader needs to make RASTERVARIABLES an object.
            let classes = groups(&bytes);
            assert!(
                classes.windows(2).any(|w| w[0] == (0, "CLASS".into()) && w[1] == (1, "RASTERVARIABLES".into())),
                "the RASTERVARIABLES class record is written"
            );
            // And the drawing it makes reads back with the mode it was saved with.
            assert_eq!(mode(&read(&bytes, "frame.dxf").unwrap()), frame);
        }
    }
}

#[test]
fn an_empty_drawing_keeps_its_mode_and_needs_no_image() {
    // The empty template case: no images at all, the setting still written and read.
    let d = drawing(Some(0), false);
    let bytes = write(&d, "empty.dxf").unwrap();
    let (frame, named, image_dict) = written(&bytes);
    assert_eq!((frame, named, image_dict), (0, true, false));
    let r = read(&bytes, "empty.dxf").unwrap();
    assert_eq!(mode(&r), 0);
    assert!(image_of(&r).is_none());
}

#[test]
fn a_mode_this_build_does_not_draw_is_written_as_the_default() {
    // A header value another reader could not use reaches the writer through the generic HEADER
    // reader: it must not be saved back as a mode of its own (0 and 2 draw differently), and it
    // must not be saved as what it is not.
    for frame in [-3, 7, i64::MAX] {
        let bytes = write(&drawing(Some(frame), false), "frame.dxf").unwrap();
        assert_eq!(written(&bytes).0, 1, "{frame} is written as the default");
        assert_eq!(mode(&read(&bytes, "frame.dxf").unwrap()), 1, "{frame} reads back as the default");
    }
}

/// A DXF file whose OBJECTS section holds a RASTERVARIABLES object with `frame` as its group 70
/// text (`None`: no RASTERVARIABLES object at all).
fn objects_file(frame: Option<&str>) -> String {
    let mut s = String::from("  0\nSECTION\n  2\nENTITIES\n  0\nENDSEC\n  0\nSECTION\n  2\nOBJECTS\n");
    if let Some(v) = frame {
        s.push_str(&format!("  0\nRASTERVARIABLES\n  5\nA1\n100\nAcDbRasterVariables\n 90\n0\n 70\n{v}\n 71\n1\n 72\n0\n"));
    }
    s.push_str("  0\nENDSEC\n  0\nEOF\n");
    s
}

fn read_both(file: &str) -> Drawing {
    cadcraft_io::read_dxf(file.as_bytes()).unwrap()
}

#[test]
fn a_missing_or_malformed_file_value_leaves_the_default() {
    for (value, want) in [
        (None, 1),
        (Some("0"), 0),
        (Some("1"), 1),
        (Some("2"), 2),
        (Some("+2"), 2),
        (Some("0000"), 0),
        (Some("-0"), 0),
        (Some("7"), 1),
        (Some("-1"), 1),
        (Some("abc"), 1),
        (Some("NaN"), 1),
        (Some("inf"), 1),
        (Some("2.5"), 1),
        (Some("1e0"), 1),
        (Some("99999999999999999999"), 1),
    ] {
        assert_eq!(mode(&read_both(&objects_file(value))), want, "{value:?}");
    }
    let padded_groups = "000\nSECTION\n002\nOBJECTS\n000\nRASTERVARIABLES\n070\n0\n000\nENDSEC\n000\nEOF\n";
    assert_eq!(mode(&read_both(padded_groups)), 0, "padded group codes are group codes");
}

#[test]
fn the_parsers_selection_decides_which_group_is_read() {
    // A record name with a `\U+` escape and a section name padded with Unicode whitespace are the
    // records the rest of the reader takes: the mode they set must be read, not replaced by a 1.
    let escaped = objects_file(Some("0")).replace("RASTERVARIABLES", "RASTER\\U+0056ARIABLES");
    assert_eq!(mode(&read_both(&escaped)), 0, "an escaped record name");
    let padded = objects_file(Some("0")).replace("\nOBJECTS\n", "\nOBJECTS\u{a0}\n");
    assert_eq!(mode(&read_both(&padded)), 0, "a section name padded with a no-break space");
    let spaced_code = objects_file(Some("0")).replace("\n 70\n", "\n\u{a0}70\n");
    assert_eq!(mode(&read_both(&spaced_code)), 0, "a group code padded with a no-break space");
    let bom = format!("\u{feff}{}", objects_file(Some("0")));
    assert_eq!(mode(&read_both(&bom)), 0, "a byte order mark");
    let crlf = objects_file(Some("0")).replace('\n', "\r\n");
    assert_eq!(mode(&read_both(&crlf)), 0, "CRLF line ends");
    let lone_cr = objects_file(Some("0")).replace('\n', "\r");
    assert_eq!(mode(&read_both(&lone_cr)), 0, "lone CR line ends");
    // A record name is compared exactly, as the reader compares it: a trailing blank is another
    // record, so the file sets no mode.
    let trailing = objects_file(Some("0")).replace("RASTERVARIABLES", "RASTERVARIABLES ");
    assert_eq!(mode(&read_both(&trailing)), 1, "a record name with a trailing blank is not it");
    // Only the first group 70 of the last record is the mode.
    let both = objects_file(Some("0")).replace("  0\nENDSEC", "  0\nRASTERVARIABLES\n 70\n2\n  0\nENDSEC");
    assert_eq!(mode(&read_both(&both)), 2, "the last record wins");
    let twice = objects_file(Some("0")).replace(" 90\n0\n", " 90\n0\n 70\n2\n");
    assert_eq!(mode(&read_both(&twice)), 2, "the record's first group 70");
}

#[test]
fn a_legacy_code_page_keeps_the_mode_it_sets() {
    // The file is not UTF-8: a comment holds a Latin-1 byte. Its groups are still the ones the
    // parser reads, so the mode is read from the spelling it has.
    let header = "  0\nSECTION\n  2\nHEADER\n  9\n$DWGCODEPAGE\n  3\nANSI_1252\n  9\n$ACADVER\n  1\nAC1015\n  0\nENDSEC\n";
    let file = |frame: &str| {
        let objects = objects_file(Some(frame)).replace("  2\nENTITIES\n", "  2\nENTITIES\n999\ncafX\n");
        let mut bytes = format!("{header}{objects}").into_bytes();
        if let Some(at) = bytes.windows(4).position(|w| w == b"cafX") {
            bytes[at + 3] = 0xE9;
        }
        assert!(std::str::from_utf8(&bytes).is_err(), "the fixture is not UTF-8");
        cadcraft_io::read_dxf(&bytes).unwrap()
    };
    assert_eq!(mode(&file("0")), 0, "a legacy code page keeps the mode it sets");
    assert_eq!(mode(&file("abc")), 1, "and a value that is no mode still leaves the default");
}

#[test]
fn legacy_whitespace_uses_the_same_decoder_as_the_drawing() {
    let file = |page: &str, code: &[u8], value: &[u8]| {
        let mut bytes = format!("0\nSECTION\n2\nHEADER\n9\n$DWGCODEPAGE\n3\n{page}\n9\n$ACADVER\n1\nAC1015\n999\n").into_bytes();
        // Force the source file's legacy-decoding path, including when this field alone is UTF-8.
        bytes.extend_from_slice(b"\xFF\n0\nENDSEC\n0\nSECTION\n2\nOBJECTS\n0\nRASTERVARIABLES\n");
        bytes.extend_from_slice(code);
        bytes.push(b'\n');
        bytes.extend_from_slice(value);
        bytes.extend_from_slice(b"\n0\nENDSEC\n0\nEOF\n");
        bytes
    };
    for (case, page, code, value, want) in [
        ("Windows no-break spaces in value", "ANSI_1252", b"70".as_slice(), b"\xA00\xA0".as_slice(), 0),
        ("Windows no-break spaces in code", "ANSI_1252", b"\xA070\xA0", b"2", 2),
        ("Windows blank code line", "ANSI_1252", b"\xA0\n70", b"2", 2),
        ("DOS no-break spaces", "DOS437", b"70", b"\xFF2\xFF", 2),
        ("DOS letters are not spaces", "DOS866", b"70", b"\xA00\xA0", 1),
        ("Shift-JIS spaces", "ANSI_932", b"70", b"\x81\x400\x81\x40", 0),
        ("Shift-JIS blank code line", "ANSI_932", b"\x81\x40\n70", b"0", 0),
        ("Johab blank code line", "ANSI_1361", b"\xD9\x31\n70", b"0", 0),
        ("Shift-JIS does not switch one line to UTF-8", "ANSI_932", b"70", b"\xC2\xA00\xC2\xA0", 1),
        ("Windows preserves a UTF-8 line", "ANSI_1252", b"70", b"\xC2\xA00\xC2\xA0", 0),
        ("Unknown code page uses Windows fallback", "UNKNOWN", b"70", b"\xA00\xA0", 0),
        ("Numeric fields do not unescape", "ANSI_1252", b"70", b"\xA0\\U+0030\xA0", 1),
    ] {
        let bytes = file(page, code, value);
        assert_eq!(mode(&cadcraft_io::read_dxf(&bytes).unwrap()), want, "{case}");
    }
    // A decoded header name is not the raw name the codec sniff uses.
    let escaped = file("DOS866", b"70", b"\xA00\xA0");
    let escaped = escaped
        .windows(b"$DWGCODEPAGE".len())
        .position(|w| w == b"$DWGCODEPAGE")
        .map(|at| {
            let mut bytes = escaped.clone();
            bytes.splice(at..at + b"$DWGCODEPAGE".len(), b"$DWGCO\\U+0044EPAGE".iter().copied());
            bytes
        })
        .unwrap();
    assert_eq!(mode(&cadcraft_io::read_dxf(&escaped).unwrap()), 0, "an escaped name leaves the codec fallback");
    let double_bom = format!("\u{feff}\u{feff}{}", objects_file(Some("0")));
    assert_eq!(mode(&read_both(&double_bom)), 0, "the byte and decoded BOMs are both skipped");
    for (padding, want) in [(4 * 1024, 0), (64 * 1024, 1)] {
        let mut value = vec![0xA0; padding];
        value.push(b'0');
        let bytes = file("ANSI_1252", b"70", &value);
        assert_eq!(mode(&cadcraft_io::read_dxf(&bytes).unwrap()), want, "legacy padding {padding}: oversized text uses the default");
    }
}

#[test]
fn a_header_tag_does_not_decide_the_mode() {
    let with_header = |frame: &str, object: Option<&str>| {
        let mut s = format!("  0\nSECTION\n  2\nHEADER\n  9\n$IMAGEFRAME\n 70\n{frame}\n  0\nENDSEC\n");
        s.push_str(&objects_file(object));
        s
    };
    // No RASTERVARIABLES object: the file sets no mode, whatever its HEADER says.
    assert_eq!(mode(&read_both(&with_header("2", None))), 1, "a HEADER tag alone is not the mode");
    // A valid object value wins over a conflicting HEADER tag.
    assert_eq!(mode(&read_both(&with_header("2", Some("0")))), 0, "the object's mode wins");
    // An object value that is no mode leaves the default, not the HEADER tag.
    assert_eq!(mode(&read_both(&with_header("0", Some("abc")))), 1, "an unusable object value");
}

#[test]
fn a_binary_dxf_keeps_the_mode_it_holds() {
    for frame in [0, 1, 2] {
        let d = drawing(Some(frame), true);
        let opts = SaveOptions { binary: true, ..SaveOptions::default() };
        let bytes = cadcraft_io::write_with(&d, "frame.dxf", &opts).unwrap();
        assert!(bytes.starts_with(b"AutoCAD Binary DXF"), "the file is binary DXF");
        let r = read(&bytes, "frame.dxf").unwrap();
        assert_eq!(mode(&r), frame, "a binary group is already a number");
        same_image(&image(), &image_of(&r).expect("the image survives"), "binary DXF");
    }
}

// ---------------- plots: the frames a plot leaves out ----------------

/// An image with square axes, wholly inside the viewport the plot test puts over it, so its frame
/// is one stroke.
fn plain_image() -> Image {
    Image {
        insert: Vec3::new(10.0, 20.0, 0.0),
        u: Vec3::new(1.0, 0.0, 0.0),
        v: Vec3::new(0.0, 1.0, 0.0),
        size: Vec2::new(4.0, 3.0),
        path: "maps/map.png".into(),
        name: "map".into(),
        ..Image::default()
    }
}

/// A layout of one drawing: `paper` puts the image on the layout itself, else model space holds it
/// and the layout sees it through a viewport. `frame` is the drawing's IMAGEFRAME.
fn layout(paper: bool, frame: i64) -> (Drawing, Space) {
    let mut d = Drawing::new_imperial();
    d.header.set_i64("IMAGEFRAME", frame);
    if paper {
        d.add(&Space::Paper("Layout1".into()), Common::default(), EntityKind::Image(plain_image())).unwrap();
    } else {
        d.add(&Space::Model, Common::default(), EntityKind::Image(plain_image())).unwrap();
        let vp = Viewport {
            center: Vec3::new(12.0, 21.5, 0.0),
            width: 20.0,
            height: 20.0,
            view_center: Vec2::new(12.0, 21.5),
            view_height: 20.0,
            id: 2,
            locked: false,
            frozen_layers: Vec::new(),
            layer_colors: Vec::new(),
            clip: None,
            on: true,
            twist: 0.0,
        };
        d.add(&Space::Paper("Layout1".into()), Common::default(), EntityKind::Viewport(vp)).unwrap();
    }
    d.rasters.insert("maps/map.png", std::sync::Arc::new(cadcraft_doc::Raster::new(4, 3, vec![200u8; 48]).unwrap()));
    (d, Space::Paper("Layout1".into()))
}

#[test]
fn a_layouts_svg_plot_leaves_out_mode_2_frames() {
    for paper in [true, false] {
        // The plotted SVG of the layout, with the strokes it draws.
        let plot = |frame: i64| {
            let (d, space) = layout(paper, frame);
            let svg = plotter::plot(&d, &space, &json!({ "output": "svg" })).expect("the layout plots");
            let strokes = String::from_utf8_lossy(&svg).matches("<polyline").count();
            (strokes, svg)
        };
        let (zero, svg_zero) = plot(0);
        let (one, svg_one) = plot(1);
        let (two, svg_two) = plot(2);
        assert_eq!(plot(0).1, svg_zero, "the same drawing plots the same bytes");
        // One image: shown and plotted in mode 1, left out of a plot in modes 0 and 2.
        assert_eq!(one, zero + 1, "paper {paper}: mode 1 draws the frame, mode 0 does not");
        assert_ne!(svg_one, svg_zero, "paper {paper}: the frame is in the plot");
        assert_eq!(svg_two, svg_zero, "paper {paper}: a plot of mode 2 draws what mode 0 draws");
        assert_eq!(two, zero, "paper {paper}: mode 2 plots no frame");
    }
}
