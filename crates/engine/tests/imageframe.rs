//! IMAGEFRAME: the drawing's raster image frame mode (0 = no frame, 1 = shown and plotted,
//! 2 = shown but not plotted, default 1) as a system variable — the IMAGEFRAME command, SETVAR,
//! GETVAR, typed input and AutoLISP's `setvar`/`getvar` — and what a wrong value leaves behind:
//! nothing, neither the drawing nor the dirty flag nor either history.

use std::sync::Arc;

use cadcraft_engine::Session;
use cadcraft_engine::cmd::file::{IoHooks, set_io};
use cadcraft_engine::doc::Drawing;
use cadcraft_engine::lisp::value::to_text;
use serde_json::{Value, json};

#[path = "support/temp_dir.rs"]
mod temp_dir;

use temp_dir::TempDir;

// Keep this real-format suite in its own process: file::set_io uses a OnceLock,
// while the shared integration binary installs mock hooks for other command tests.
fn hooks() {
    // The DWG bridge sees only the small drawings generated by this test process.
    cadcraft_io::dwg_worker::allow_in_process();
    set_io(IoHooks {
        read: |b, name| cadcraft_io::read(b, name).map_err(|e| e.to_string()),
        write: |d, name| cadcraft_io::write(d, name).map_err(|e| e.to_string()),
        plot: None,
    });
}

/// The mode the drawing holds, as GETVAR reports it.
fn mode(s: &mut Session) -> i64 {
    s.execute("getvar", &json!({ "name": "IMAGEFRAME" })).unwrap()["value"].as_i64().unwrap()
}

/// How many steps each history holds: (undo, redo).
fn histories(s: &Session) -> (usize, usize) {
    let st = s.state().unwrap();
    (st.undo.len(), st.redo.len())
}

/// The open drawing itself, to tell whether a command touched it at all.
fn drawing(s: &Session) -> Arc<Drawing> {
    s.state().unwrap().doc.clone()
}

/// Evaluate LISP source: its value as `prin1` shows it, or the error message.
fn lisp(s: &mut Session, code: &str) -> Result<String, String> {
    match s.lisp_eval(code, false, true, Vec::new()) {
        Ok(Some(Ok(v))) => Ok(to_text(&v, true)),
        Ok(Some(Err(e))) => Err(e),
        Ok(None) => Err("did not finish".to_string()),
        Err(e) => Err(e.to_string()),
    }
}

/// A drawing saved with the mode, then opened again in a fresh session.
fn reopened(dir: &TempDir, name: &str, frame: i64) -> Session {
    let mut s = Session::new();
    s.execute("imageframe", &json!({ "value": frame })).unwrap();
    let path = dir.path_str(name);
    s.execute("saveas", &json!({ "path": path })).unwrap();
    assert!(!s.state().unwrap().is_dirty(), "saved");
    let mut opened = Session::new();
    opened.execute("open", &json!({ "path": path })).unwrap();
    opened
}

#[test]
fn the_default_is_one_and_asking_for_it_changes_nothing() {
    let mut s = Session::new();
    assert_eq!(mode(&mut s), 1, "a drawing without the setting shows frames");
    let d = drawing(&s);
    let before = histories(&s);
    assert_eq!(s.execute("imageframe", &json!({})).unwrap()["value"], 1, "no value asks for the mode");
    assert_eq!(s.execute("getvar", &json!({ "name": "imageframe" })).unwrap()["value"], 1);
    assert!(s.execute("setvar", &json!({ "name": "IMAGEFRAME", "value": Value::Null })).is_err(), "an explicit null value is not the mode");
    assert!(Arc::ptr_eq(&d, &drawing(&s)), "the drawing was not touched");
    assert_eq!(histories(&s), before, "and no step was recorded");
    assert!(!s.state().unwrap().is_dirty());
}

#[test]
fn the_command_and_setvar_set_each_mode() {
    let mut s = Session::new();
    for m in [0, 2, 1] {
        assert_eq!(s.execute("imageframe", &json!({ "value": m })).unwrap()["value"], m);
        assert_eq!(mode(&mut s), m);
    }
    for m in [2, 0] {
        let r = s.execute("setvar", &json!({ "name": "IMAGEFRAME", "value": m })).unwrap();
        assert_eq!(r["value"], m);
        assert_eq!(mode(&mut s), m);
    }
    assert!(s.state().unwrap().is_dirty(), "the setting is part of the drawing");
}

#[test]
fn typed_input_gives_a_number_not_text() {
    let mut s = Session::new();
    // The command asks for the mode with the current one as the default.
    s.cmdline("IMAGEFRAME").unwrap();
    assert_eq!(s.current_prompt().unwrap().display(), "Enter image frame setting or [0/1/2] <1>:");
    s.cmdline("0").unwrap();
    assert!(s.current_prompt().is_none());
    assert_eq!(mode(&mut s), 0);

    // SETVAR's value prompt hands its answer over as text; the typed integer becomes the mode.
    s.cmdline("SETVAR").unwrap();
    assert!(s.current_prompt().unwrap().display().starts_with("Enter variable name"), "{}", s.prompt_text());
    s.cmdline("IMAGEFRAME").unwrap();
    assert_eq!(s.current_prompt().unwrap().display(), "Enter new value for IMAGEFRAME <0>:");
    s.cmdline("2").unwrap();
    assert!(s.current_prompt().is_none());
    assert_eq!(mode(&mut s), 2);

    // A value that is no mode keeps the prompt and the drawing, and the next answer finishes.
    s.cmdline("IMAGEFRAME").unwrap();
    s.cmdline("3").unwrap();
    assert!(s.current_prompt().is_some(), "it asks again");
    assert_eq!(mode(&mut s), 2, "unchanged");
    s.cmdline("1").unwrap();
    assert!(s.current_prompt().is_none());
    assert_eq!(mode(&mut s), 1);
}

#[test]
fn lisp_setvar_and_getvar_reach_the_same_setting() {
    let mut s = Session::new();
    assert_eq!(lisp(&mut s, "(getvar \"IMAGEFRAME\")").unwrap(), "1");
    lisp(&mut s, "(setvar \"IMAGEFRAME\" 0)").unwrap();
    assert_eq!(mode(&mut s), 0);
    assert_eq!(lisp(&mut s, "(getvar \"IMAGEFRAME\")").unwrap(), "0");
    lisp(&mut s, "(setvar \"IMAGEFRAME\" 2)").unwrap();
    assert_eq!(mode(&mut s), 2, "an integer argument is the mode");
}

#[test]
fn a_wrong_value_leaves_the_drawing_and_both_histories_alone() {
    let mut s = Session::new();
    // A step to undo, so redo holds one: a rejected value must not throw it away.
    s.execute("line", &json!({ "points": [[0, 0], [10, 0]] })).unwrap();
    s.execute("undo", &json!({})).unwrap();
    assert_eq!(histories(&s), (0, 1), "one step waits to be redone");
    let dirty = s.state().unwrap().is_dirty();
    let d = drawing(&s);
    // -1, out of range, a fraction, a float spelling, text, a Boolean, null, an array, an object and
    // a number that is not an integer any more.
    let bad = [
        json!(-1),
        json!(3),
        json!(1.5),
        json!(2.0),
        json!("2"),
        json!(""),
        json!(true),
        json!(false),
        Value::Null,
        json!([2]),
        json!({ "value": 2 }),
        json!(u64::MAX),
    ];
    for b in &bad {
        for (id, p) in [("imageframe", json!({ "value": b })), ("setvar", json!({ "name": "IMAGEFRAME", "value": b }))] {
            assert!(s.execute(id, &p).is_err(), "{id} took {b}");
            assert_eq!(mode(&mut s), 1, "{id} with {b}: the mode");
            assert!(Arc::ptr_eq(&d, &drawing(&s)), "{id} with {b}: the drawing");
            assert_eq!(histories(&s), (0, 1), "{id} with {b}: the histories");
            assert_eq!(s.state().unwrap().is_dirty(), dirty, "{id} with {b}: the dirty flag");
        }
    }
    // AutoLISP's `setvar` goes through the same validation.
    for expr in [
        "(setvar \"IMAGEFRAME\" \"2\")",
        "(setvar \"IMAGEFRAME\" T)",
        "(setvar \"IMAGEFRAME\" nil)",
        "(setvar \"IMAGEFRAME\" 1.5)",
        "(setvar \"IMAGEFRAME\" 2.0)",
        "(setvar \"IMAGEFRAME\" '(2))",
        "(setvar \"IMAGEFRAME\" -1)",
        "(setvar \"IMAGEFRAME\" 3)",
        "(setvar \"IMAGEFRAME\" 99999999999999999999)",
    ] {
        assert!(lisp(&mut s, expr).is_err(), "{expr}");
        assert_eq!(mode(&mut s), 1, "{expr}: the mode");
        assert!(Arc::ptr_eq(&d, &drawing(&s)), "{expr}: the drawing");
        assert_eq!(histories(&s), (0, 1), "{expr}: the histories");
    }
    // Typed at SETVAR's value prompt, a wrong entry is reported and asks again, and the step that
    // waits to be redone is still there.
    s.cmdline("SETVAR").unwrap();
    s.cmdline("IMAGEFRAME").unwrap();
    s.cmdline("abc").unwrap();
    assert!(s.current_prompt().is_some(), "it asks again");
    assert_eq!(mode(&mut s), 1, "the typed wrong value changed nothing");
    assert_eq!(histories(&s), (0, 1), "nor did it discard the redo");
    s.cmdline("").unwrap();
    assert!(s.current_prompt().is_none());
    // The step that was waiting still runs.
    s.execute("redo", &json!({})).unwrap();
    assert_eq!(s.doc().unwrap().model.iter().count(), 1, "the redo was not lost");
}

#[test]
fn undo_and_redo_take_the_mode_with_them() {
    let mut s = Session::new();
    assert_eq!(mode(&mut s), 1);
    s.execute("imageframe", &json!({ "value": 0 })).unwrap();
    assert_eq!(mode(&mut s), 0);
    s.execute("undo", &json!({})).unwrap();
    assert_eq!(mode(&mut s), 1, "undo puts the mode back");
    s.execute("redo", &json!({})).unwrap();
    assert_eq!(mode(&mut s), 0, "redo sets it again");

    // SETVAR records a step of its own, and the typed command does too.
    s.execute("setvar", &json!({ "name": "IMAGEFRAME", "value": 2 })).unwrap();
    assert_eq!(mode(&mut s), 2);
    s.execute("undo", &json!({})).unwrap();
    assert_eq!(mode(&mut s), 0);
    s.cmdline("IMAGEFRAME").unwrap();
    s.cmdline("1").unwrap();
    assert_eq!(mode(&mut s), 1);
    s.execute("undo", &json!({})).unwrap();
    assert_eq!(mode(&mut s), 0);
}

#[test]
fn the_mode_survives_saveas_open_and_a_new_drawing_from_a_template() {
    hooks();
    let dir = TempDir::new("imageframe");
    // No image in the drawing: the setting is the drawing's, not any image's.
    for (name, frame) in [("frame.dxf", 0), ("frame.dwg", 2), ("frame.dwt", 0)] {
        let mut opened = reopened(&dir, name, frame);
        assert_eq!(mode(&mut opened), frame, "{name}");
        assert_eq!(opened.doc().unwrap().model.iter().count(), 0, "{name}: no image");
    }

    // A template an empty drawing starts from carries the setting.
    let mut t = Session::new();
    t.execute("imageframe", &json!({ "value": 2 })).unwrap();
    let dwt = dir.path_str("house.dwt");
    t.execute("saveas", &json!({ "path": dwt })).unwrap();
    let mut from = Session::new();
    from.execute("new", &json!({ "template": dwt })).unwrap();
    assert_eq!(mode(&mut from), 2, "an empty template keeps its image frame setting");
    assert_eq!(from.doc().unwrap().model.iter().count(), 0);

    // QNEW from the default template does the same.
    from.execute("setvar", &json!({ "name": "QNEWTEMPLATE", "value": dwt })).unwrap();
    from.execute("imageframe", &json!({ "value": 0 })).unwrap();
    from.cmdline("qnew").unwrap();
    assert_eq!(mode(&mut from), 2, "QNEW starts from the template's setting");

    // A file that sets no mode reads back as the default, not as whatever the saved one was.
    let mut plain = Session::new();
    plain.execute("imageframe", &json!({ "value": 0 })).unwrap();
    let dxf = dir.path_str("plain.dxf");
    plain.execute("saveas", &json!({ "path": dxf })).unwrap();
    let mut back = Session::new();
    back.execute("open", &json!({ "path": dxf })).unwrap();
    assert_eq!(mode(&mut back), 0, "the saved mode is in the file");
}
