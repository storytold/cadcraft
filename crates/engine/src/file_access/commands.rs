/// Why command `id` may not run here; `None` when it may. Without roots in force everything may.
pub fn refusal(id: &str) -> Option<String> {
    super::current()?;
    if let Some((_, why)) = REFUSED.iter().find(|(c, _)| *c == id) {
        return Some(format!("automation command refused: {why}"));
    }
    if FILES.contains(&id) || NO_FILES.contains(&id) {
        return None;
    }
    Some("automation command refused: it is not classified for the automation roots".to_string())
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::panic)]
mod tests {
    use super::super::{AutomationRoots, confine};
    use super::*;
    use std::collections::BTreeSet;

    /// Words in a command's parameter doc that usually name a file. In these commands they don't:
    /// `array` and `arraypath` follow a path of objects, and `blocks.reference.grips` reports a
    /// direction.
    const NOT_FILES: &[&str] = &["array", "arraypath", "blocks.reference.grips"];

    fn words(doc: &str) -> BTreeSet<String> {
        doc.to_ascii_lowercase().split(|c: char| !c.is_ascii_alphanumeric()).map(str::to_string).collect()
    }

    /// Walks the registry: every command is on exactly one list, and the lists name no command
    /// that is gone. A command whose parameters name a file can't be on the no-files list.
    #[test]
    fn every_command_is_classified() {
        let refused: Vec<&str> = REFUSED.iter().map(|(c, _)| *c).collect();
        let lists = [FILES, refused.as_slice(), NO_FILES];
        let specs = crate::command_specs();
        for spec in specs {
            let on = lists.iter().filter(|l| l.contains(&spec.id)).count();
            assert_eq!(on, 1, "`{}` is on {on} lists: add it to one in file_access/commands.rs", spec.id);
            let doc = words(spec.params);
            let names_a_file = ["path", "file", "template", "patternfile", "folder", "dir"].iter().any(|w| doc.contains(*w));
            if names_a_file && NO_FILES.contains(&spec.id) && !NOT_FILES.contains(&spec.id) {
                panic!("`{}` takes a file ({}): it belongs on FILES, with its paths checked", spec.id, spec.params);
            }
        }
        for id in lists.iter().flat_map(|l| l.iter()) {
            assert!(specs.iter().any(|s| s.id == *id), "`{id}` is listed but no longer a command");
        }
    }

    /// Under roots a command nobody classified is refused; without roots it isn't this table's business.
    #[test]
    fn an_unclassified_command_fails_closed() {
        let base = std::env::temp_dir().join(format!("cc-commands-{}", std::process::id()));
        std::fs::create_dir_all(&base).unwrap();
        let roots = AutomationRoots::new(Some(&base), None).unwrap();
        assert_eq!(refusal("made.up"), None);
        confine(roots.as_ref(), || {
            assert!(refusal("made.up").unwrap().contains("not classified"));
            assert!(refusal("drawingrecovery").unwrap().contains("autosave"));
            assert_eq!(refusal("open"), None);
            assert_eq!(refusal("line"), None);
        });
        let _ = std::fs::remove_dir_all(base);
    }
}
